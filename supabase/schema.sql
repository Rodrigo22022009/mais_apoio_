create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null,
  username text unique,
  email text,
  phone text,
  address text,
  city text,
  role text not null default 'beneficiario'
    check (role in ('admin', 'beneficiario', 'medico', 'enfermeiro', 'coordenador')),
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now()
);

create table if not exists public.beneficiaries (
  id bigint generated by default as identity primary key,
  profile_id uuid references public.profiles(id) on delete set null,
  name text not null,
  birth_date date,
  phone text,
  email text,
  address text,
  city text,
  emergency_contact text,
  need text not null default 'Cuidados médicos',
  priority text not null default 'Média' check (priority in ('Alta', 'Média', 'Baixa')),
  notes text,
  created_at timestamptz not null default now()
);

create table if not exists public.volunteers (
  id bigint generated by default as identity primary key,
  profile_id uuid unique references public.profiles(id) on delete cascade,
  name text not null,
  specialty text not null,
  phone text,
  email text,
  city text,
  registration_number text,
  areas text,
  availability text not null default 'Disponível'
    check (availability in ('Disponível', 'Em atendimento', 'Indisponível')),
  created_at timestamptz not null default now()
);

create table if not exists public.support_requests (
  id bigint generated by default as identity primary key,
  beneficiary_id bigint references public.beneficiaries(id) on delete set null,
  subject text not null,
  description text not null,
  priority text not null default 'Média' check (priority in ('Alta', 'Média', 'Baixa')),
  status text not null default 'Pendente'
    check (status in ('Pendente', 'Em análise', 'Aceite', 'Concluído', 'Cancelado')),
  created_at timestamptz not null default now()
);

create table if not exists public.supports (
  id bigint generated by default as identity primary key,
  beneficiary_id bigint not null references public.beneficiaries(id) on delete cascade,
  volunteer_id bigint references public.volunteers(id) on delete set null,
  type text not null default 'Cuidados médicos',
  scheduled_at timestamptz not null,
  status text not null default 'Agendado'
    check (status in ('Agendado', 'Realizado', 'Cancelado')),
  notes text,
  created_at timestamptz not null default now()
);

create table if not exists public.ratings (
  id bigint generated by default as identity primary key,
  support_id bigint not null references public.supports(id) on delete cascade,
  author_id uuid not null references auth.users(id) on delete cascade,
  stars integer not null check (stars between 1 and 5),
  comment text,
  created_at timestamptz not null default now(),
  unique (support_id, author_id)
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  profile_id uuid not null references public.profiles(id) on delete cascade,
  title text not null,
  message text not null,
  read_at timestamptz,
  created_at timestamptz not null default now()
);

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select exists (
  select 1 from public.profiles
  where id = auth.uid() and role in ('admin', 'coordenador') and status = 'approved'
) $$;

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  insert into public.profiles (id, name, username, email, phone, role, status)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'name', split_part(new.email, '@', 1)),
    new.raw_user_meta_data->>'username',
    new.email,
    new.raw_user_meta_data->>'phone',
    coalesce(new.raw_user_meta_data->>'role', 'beneficiario'),
    'pending'
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

alter table public.profiles enable row level security;
alter table public.beneficiaries enable row level security;
alter table public.volunteers enable row level security;
alter table public.support_requests enable row level security;
alter table public.supports enable row level security;
alter table public.ratings enable row level security;
alter table public.notifications enable row level security;

create policy "profiles read own or admin" on public.profiles for select
  using (id = auth.uid() or public.is_admin());
create policy "profiles update own or admin" on public.profiles for update
  using (id = auth.uid() or public.is_admin());
create policy "admin manages profiles" on public.profiles for all
  using (public.is_admin()) with check (public.is_admin());

create policy "authenticated read beneficiaries" on public.beneficiaries for select
  using (auth.uid() is not null);
create policy "admin or coordinator manage beneficiaries" on public.beneficiaries for all
  using (public.is_admin()) with check (public.is_admin());
create policy "beneficiary creates own record" on public.beneficiaries for insert
  with check (profile_id = auth.uid());

create policy "authenticated read volunteers" on public.volunteers for select
  using (auth.uid() is not null);
create policy "admin manages volunteers" on public.volunteers for all
  using (public.is_admin()) with check (public.is_admin());
create policy "volunteer updates own record" on public.volunteers for update
  using (profile_id = auth.uid()) with check (profile_id = auth.uid());

create policy "users read relevant requests" on public.support_requests for select
  using (public.is_admin() or exists (
    select 1 from public.beneficiaries b
    where b.id = beneficiary_id and b.profile_id = auth.uid()
  ));
create policy "beneficiary creates request" on public.support_requests for insert
  with check (exists (
    select 1 from public.beneficiaries b
    where b.id = beneficiary_id and b.profile_id = auth.uid()
  ));
create policy "admin manages requests" on public.support_requests for all
  using (public.is_admin()) with check (public.is_admin());

create policy "users read relevant supports" on public.supports for select
  using (public.is_admin() or exists (
    select 1 from public.beneficiaries b
    where b.id = beneficiary_id and b.profile_id = auth.uid()
  ) or exists (
    select 1 from public.volunteers v
    where v.id = volunteer_id and v.profile_id = auth.uid()
  ));
create policy "admin manages supports" on public.supports for all
  using (public.is_admin()) with check (public.is_admin());
create policy "volunteer updates assigned support" on public.supports for update
  using (exists (select 1 from public.volunteers v where v.id = volunteer_id and v.profile_id = auth.uid()))
  with check (exists (select 1 from public.volunteers v where v.id = volunteer_id and v.profile_id = auth.uid()));

create policy "users read ratings for relevant support" on public.ratings for select
  using (author_id = auth.uid() or public.is_admin());
create policy "user creates rating" on public.ratings for insert
  with check (author_id = auth.uid());
create policy "admin manages ratings" on public.ratings for all
  using (public.is_admin()) with check (public.is_admin());

create policy "users read own notifications" on public.notifications for select
  using (profile_id = auth.uid() or public.is_admin());
create policy "users update own notifications" on public.notifications for update
  using (profile_id = auth.uid() or public.is_admin());
create policy "admin creates notifications" on public.notifications for insert
  with check (public.is_admin());

create index if not exists beneficiaries_profile_id_idx on public.beneficiaries(profile_id);
create index if not exists supports_scheduled_at_idx on public.supports(scheduled_at);
create index if not exists support_requests_status_idx on public.support_requests(status);
